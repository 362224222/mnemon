func TestLoadHarnessSourcesUsesExplicitMetricExclusions(t *testing.T) {
	root := t.TempDir()
	writeTestFile(t, root, "harness/kept.go", "package harness\nfunc kept() {}\n")
	writeTestFile(t, root, "harness/kept_test.go", "package harness\nfunc TestKept() {}\n")
	writeTestFile(t, root, "harness/generated.go", "// Code generated by fixture. DO NOT EDIT.\npackage harness\n")
	writeTestFile(t, root, "harness/testdata/ignored.go", "package ignored\n")
	writeTestFile(t, root, "harness/.projection/ignored.go", "package ignored\n")
	writeCanonicalTestFile(t, root, exclusionsPath, exclusionManifest{SchemaVersion: 1, Entries: []exclusionEntry{
		{Path: "harness/generated.go", Kind: exclusionGenerated, Reason: "generated fixture", Owner: "test"},
		{Path: "harness/testdata/ignored.go", Kind: exclusionTestdata, Reason: "parser fixture", Owner: "test"},
	}})

	files, err := loadHarnessSources(root)
	if err != nil {
		t.Fatal(err)
	}
	if len(files) != 4 {
		t.Fatalf("loaded paths = %#v", sourcePaths(files))
	}
	eligible := metricEligibleSources(files)
	if len(eligible) != 2 || eligible[0].Path != "harness/kept.go" || eligible[1].Path != "harness/kept_test.go" {
		t.Fatalf("metric paths = %#v", sourcePaths(eligible))
	}
	if eligible[0].LineCount != 2 || !eligible[1].IsTest {
		t.Fatalf("source metadata = %#v / %#v", eligible[0], eligible[1])
	}
}

