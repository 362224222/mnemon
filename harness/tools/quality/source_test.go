func TestGeneratedDetectionRequiresCanonicalHeaderBeforePackage(t *testing.T) {
	if !isGeneratedSource([]byte("// Code generated by fixture. DO NOT EDIT.\npackage generated\n")) {
		t.Fatal("canonical generated header was not detected")
	}
	spoof := []byte("package harness\nconst text = `// Code generated by fixture. DO NOT EDIT.`\n")
	if isGeneratedSource(spoof) {
		t.Fatal("generated phrase in source content was trusted")
	}
	blockSpoof := []byte("/*\n// Code generated by fixture. DO NOT EDIT.\n*/\npackage harness\n")
	if isGeneratedSource(blockSpoof) {
		t.Fatal("line-shaped text inside a block comment was trusted as a generated directive")
	}
}

